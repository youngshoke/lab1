def count_occurrences(data, target):
    """
    Рекурсивно подсчитывает, сколько раз target встречается в списке data
    произвольной вложенности.

    Базовый случай: элемент не является списком -> сравниваем с target.
    Рекурсивный случай: элемент является списком -> суммируем результаты
    рекурсивных вызовов по его элементам.
    """
    if not isinstance(data, list):
        return 1 if data == target else 0
    return sum(count_occurrences(item, target) for item in data)


if __name__ == "__main__":
    data = [1, [2, 1, [1, 3]], 1, [4, [1, 1]]]
    target = 1

    result = count_occurrences(data, target)
    print(f"count_occurrences({data}, {target}) = {result}")

    # Примечание: в методичке указан ожидаемый результат 5, но при честном
    # подсчёте вхождений числа 1 в data их фактически 6 (проверьте вручную:
    # 1, [2,1,[1,3]] -> 1,1, 1, [4,[1,1]] -> 1,1 = 6 штук). Похоже, в условии
    # опечатка. Код и подсчёт корректны — оставлен фактический результат.
    assert result == 6
    print("Проверка пройдена успешно.")
